"""Extension template for observational (real) causal datasets.

Purpose of this template
------------------------
Use this file as a starting point when adding a dataset under
``skcausal.datasets`` whose covariates, treatments, and outcomes are *given* —
a table you loaded from disk, a vendored CSV, a study extract — rather than
generated by a data-generating process you control.

Use this only when the outcomes are the observed ones. If you simulate the
outcome from a response surface you control, that surface is ground truth and
should be exposed: subclass ``BaseKnownResponseDataset``, which adds
``predict_y`` and ``predict_curve`` on top of what is templated here. Use
``synthetic_dataset.py`` when the covariates are generated too, and
``semi_synthetic_dataset.py`` when they come from a supervised source.

How to use this template
------------------------
1. Copy the file to a module with a descriptive name.
2. Rename ``MyObservationalDataset``.
3. Update the module and class docstrings, and cite the data source.
4. Define ``column_types`` for the treatment table using ``"continuous"`` or
   ``"categorical"`` values.
5. Implement ``_load``.
6. Add ``get_test_params`` so the dataset can be instantiated in local tests.

Repo-specific contract notes
----------------------------
* ``load`` coerces whatever ``_load`` returns to the configured backend, so
  ``_load`` may return numpy arrays or polars/pandas frames.
* The treatment frame is renamed to the keys of ``column_types`` and cast to
  the declared dtypes; return its columns in that order.
* ``load_covariates_and_outcome`` is inherited and drops the treatment, so
  supervised consumers can take this dataset too.
* The ``task`` tag names the supervised task the outcome poses; the object
  sweep in ``tests/datasets`` requires it.
* ``load`` is expected to be cheap and repeatable. Do the I/O here rather than
  in ``__init__``, so that constructing the object stays free.
"""

